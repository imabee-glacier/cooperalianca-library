//! Every portal operation the web app performs, as found in its public JavaScript bundle.
//! Paths, methods, and parameter names are copied from that bundle. Response and request-body
//! shapes are not documented by the portal, so bodies are passed through and responses returned as-is.
//! Live behavior of any operation is unverified until evidence says otherwise (see AUDIT.md).

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Method {
    Get,
    Post,
    Put,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// Does not change portal state. POST-based document generators and simulations are reads.
    Read,
    /// Changes portal state. Needs an unchanged preview and `confirm`.
    Write,
    /// Cancels, removes, or deactivates. Also needs the target restated exactly.
    Destructive,
}
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Out {
    Json,
    Pdf,
}
pub struct Op {
    pub name: &'static str,
    pub method: Method,
    /// Path under the backend API root. `{x}` segments are filled from `path` parameters.
    pub path: &'static str,
    pub path_params: &'static [&'static str],
    pub query: &'static [&'static str],
    pub optional_query: &'static [&'static str],
    pub body: bool,
    pub kind: Kind,
    pub out: Out,
    pub help: &'static str,
}
#[allow(clippy::too_many_arguments)]
const fn op(
    name: &'static str,
    method: Method,
    path: &'static str,
    path_params: &'static [&'static str],
    query: &'static [&'static str],
    body: bool,
    kind: Kind,
    help: &'static str,
) -> Op {
    Op {
        name,
        method,
        path,
        path_params,
        query,
        optional_query: &[],
        body,
        kind,
        out: Out::Json,
        help,
    }
}
const fn pdf(mut o: Op) -> Op {
    o.out = Out::Pdf;
    o
}
const fn opt(mut o: Op, optional: &'static [&'static str]) -> Op {
    o.optional_query = optional;
    o
}
